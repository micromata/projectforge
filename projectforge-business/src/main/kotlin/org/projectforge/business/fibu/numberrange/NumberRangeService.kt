package org.projectforge.business.fibu.numberrange

import jakarta.annotation.PostConstruct
import io.github.oshai.kotlinlogging.KotlinLogging
import org.projectforge.business.fibu.kost.KostCache
import org.projectforge.framework.configuration.Configuration
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.context.event.ApplicationReadyEvent
import org.springframework.boot.context.properties.bind.Binder
import org.springframework.context.event.EventListener
import org.springframework.core.env.Environment
import org.springframework.stereotype.Service

private val log = KotlinLogging.logger {}

/**
 * Provides the configured number ranges ([NumberRangeConfig]). An inconsistent configuration stops the start.
 */
@Service
open class NumberRangeService {
    @Autowired
    private lateinit var environment: Environment

    @Autowired
    private lateinit var kostCache: KostCache

    lateinit var numberRanges: NumberRanges
        private set

    @PostConstruct
    private fun postConstruct() {
        // Bound explicitly (not as @ConfigurationProperties bean), so the test context without Spring Boot gets it too:
        val config = Binder.get(environment).bind(NumberRangeConfig.PREFIX, NumberRangeConfig::class.java)
            .orElseGet { NumberRangeConfig() }
        numberRanges = NumberRanges(config.ranges, config.allowFreeNumbers, config.defaultSegments)
        if (numberRanges.isConfigured) {
            log.info { "Number ranges: ${numberRanges.ranges.joinToString()}, allowFreeNumbers=${numberRanges.allowFreeNumbers}" }
        } else {
            log.info { "No number ranges configured: customer and project numbers are free." }
        }
        instance = this
    }

    /**
     * Warns about Kost2 of projects (generated by the formerly hard-coded number ranges 4 and 5) without any
     * configured number range: no Kost2 can be generated for projects then.
     */
    @EventListener(ApplicationReadyEvent::class)
    open fun checkConfiguration() {
        if (numberRanges.isConfigured || !Configuration.instance.isCostConfigured) {
            return
        }
        val count = kostCache.getAllKost2().count { it.projekt != null }
        if (count > 0) {
            log.warn {
                "Cost units are configured and $count Kost2 of projects exist, but no number range is configured" +
                        " (projectforge.fibu.number-ranges.*): no Kost2 can be generated for projects. Configure the" +
                        " number ranges formerly built in (4: internal, 5: customers 0-999), see NumberRangeConfig."
            }
        }
    }

    companion object {
        private var instance: NumberRangeService? = null

        private val unconfigured = NumberRanges(emptyList())

        /**
         * For static helpers (formatters, parsers) that can't be injected. Without Spring context (plain unit tests)
         * no range is configured.
         */
        @JvmStatic
        val current: NumberRanges
            get() = instance?.numberRanges ?: unconfigured
    }
}
